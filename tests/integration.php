<?php
require __DIR__.'/../plugins/mcp/lib/Common.php';
require __DIR__.'/../plugins/mcp/lib/Repository.php';
require __DIR__.'/../plugins/mcp/lib/Rrd.php';
require __DIR__.'/../plugins/mcp/lib/Service.php';
require __DIR__.'/../plugins/mcp/lib/Protocol.php';
use CactiMcp\Fault;
use CactiMcp\Repository;
use CactiMcp\Input;
use CactiMcp\Protocol;
$config=CactiMcp\loadConfig();
$fixture=json_decode(file_get_contents(getenv('MCP_TEST_RUNTIME').'/client.json'),true);
$db=new CactiMcp\Db($config['database']);
$repo=new Repository($db,1);
$rrd=new CactiMcp\Rrd($config);
$svc=new CactiMcp\Service($repo,$rrd);
$count=0;
function check($truth,$message) { global $count; if (!$truth) throw new Exception('FAIL: '.$message); $count++; echo 'PASS '.$message."\n"; }
function rejects($fn,$message) { $rejected=false; try { $fn(); } catch (Fault $e) { $rejected=true; } check($rejected,$message); }
$before=array(); foreach (glob($config['rrd_root'].'/*.rrd') as $file) $before[$file]=hash_file('sha256',$file);
check(Repository::prefix(str_pad('010',90,'0'))==='010','tree prefix retains trailing zero within a tier');
$rows=$svc->call('list_scope_graphs',array('tree_id'=>2,'node_id'=>100));
check(array_column($rows['items'],'graph_id')===array(100,101,102,104),'recursive host expansion, direct graph deduplication and graph deny');
$small=$svc->call('list_scope_graphs',array('tree_id'=>2,'node_id'=>100,'limit'=>2));
check(count($small['items'])===2 && $small['next_offset']===2,'pagination');
$filtered=$svc->call('list_scope_graphs',array('tree_id'=>2,'node_id'=>102,'query_id'=>1,'snmp_index'=>'2'));
check(array_column($filtered['items'],'graph_id')===array(101),'virtual interface group selection');
$found=$svc->call('search_tree_nodes',array('query'=>'Room'));
$headers=array_filter($found['items'],function($n){return $n['kind']==='header' && $n['name']==='Room';});
check(count($headers)===2,'same-name nodes remain distinct candidates');
$hidden=$svc->call('search_tree_nodes',array('query'=>'Denied Router'));
check($hidden['total']===0,'denied host metadata is hidden');
$nonQuery=$svc->call('list_scope_graphs',array('tree_id'=>2,'node_id'=>102,'query_id'=>0));
check($nonQuery['total']===0,'query zero selects non-query graphs rather than all graphs');
$named=$svc->call('search_tree_nodes',array('query'=>'Interface - Traffic'));
check($named['total']>0,'virtual template groups are searchable by display name');
rejects(function()use($repo){$repo->scope(3,0);},'denied tree');
rejects(function()use($repo){$repo->scope(2,106);},'cross-tree node injection');
rejects(function()use($repo){$repo->graph(103);},'denied graph by direct ID');
rejects(function()use($repo){$repo->graph(105);},'denied host by direct graph ID');
rejects(function()use($db){$db->all('UPDATE user_auth SET enabled=0');},'query adapter rejects writes');
$pdo=new PDO($config['database']['dsn'],$config['database']['username'],$config['database']['password'],array(PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION));
$denied=false; try {$pdo->exec("UPDATE user_auth SET enabled=enabled WHERE id=1");}catch(PDOException $e){$denied=true;}
check($denied,'database itself denies UPDATE for endpoint credentials');
rejects(function(){Input::window(array('start'=>100,'end'=>99));},'reversed time range');
rejects(function(){Input::integer(array('graph_id'=>'1 OR 1=1'),'graph_id',1,100);},'numeric SQL injection rejected');
rejects(function()use($rrd){$rrd->path(array('data_source_path'=>'/etc/passwd'));},'RRD path escape rejected');
rejects(function()use($rrd){$rrd->path(array('data_source_path'=>''));},'empty RRD path rejected without repair');
$args=array('graph_id'=>100,'start'=>$fixture['start'],'end'=>$fixture['end'],'resolution'=>300);
$data=$svc->call('get_graph_timeseries',$args);
check($data['step']===300 && $data['unit']==='bit/s','actual RRD step and unit');
check(abs($data['statistics']['in']['average']-1000000)<0.01,'COUNTER rate converted to bit/s exactly once');
check(abs($data['statistics']['out']['peak']-8000000)<0.01,'synthetic peak value');
check($data['statistics']['out']['peak_time']===$fixture['peak_time'],'peak timestamp');
$args['graph_id']=102;
$missing=$svc->call('get_graph_timeseries',$args);
check($missing['statistics']['out']['missing_ratio']>0 && in_array(null,array_column($missing['points'],'out'),true),'unknown RRD data remains null');
$args['graph_id']=100;
$cmp=$svc->call('compare_host_interfaces',$args);
check(count($cmp['interfaces'])===3,'one interface counted once across duplicate graph views');
check($cmp['interfaces'][0]['graph_ids']===array(100,104),'duplicate graph IDs retained as provenance');
check(abs($cmp['interfaces'][1]['at_reference_peak']-6000000)<0.01,'other interface value at reference peak');
check($cmp['reference_peak_time']===$fixture['peak_time'],'aligned comparison timestamp');
$server=array('HTTP_HOST'=>'127.0.0.1:18765','HTTP_AUTHORIZATION'=>'Bearer '.$fixture['token']);
check(CactiMcp\Http::authorize($server,$config)===1,'bearer token maps to user');
$evil=$server; $evil['HTTP_ORIGIN']='https://untrusted.invalid';
rejects(function()use($evil,$config){CactiMcp\Http::authorize($evil,$config);},'untrusted Origin rejected');
$expired=$config; $expired['tokens'][0]['expires_at']=1;
rejects(function()use($server,$expired){CactiMcp\Http::authorize($server,$expired);},'expired token rejected');
$strict=$config; $strict['allow_plain_http']=false;
rejects(function()use($server,$strict){CactiMcp\Http::authorize($server,$strict);},'plaintext disabled by default');
$notification=json_decode('{"jsonrpc":"2.0","method":"tools/call","params":{"name":"get_graph_image","arguments":{}}}');
check(Protocol::dispatch($notification,$svc)===null,'notifications never invoke tools or produce a response');
$invalid=Protocol::dispatch(json_decode('{"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"get_graph_timeseries","arguments":{"graph_id":100,"start":1,"end":2,"file":"/etc/passwd"}}}'),$svc);
check($invalid['result']['isError']===true,'additional tool arguments rejected');
$imageArgs=$args; unset($imageArgs['resolution']);
$png=$svc->call('get_graph_image',$imageArgs);
check(substr(base64_decode($png['_image']),0,8)==="\x89PNG\r\n\x1a\n",'original Cacti renderer returns PNG for dates beyond legacy timestamp cap');
file_put_contents(getenv('MCP_TEST_RUNTIME').'/graph.png',base64_decode($png['_image']));
$after=array(); foreach (glob($config['rrd_root'].'/*.rrd') as $file) $after[$file]=hash_file('sha256',$file);
check($before===$after,'RRD files unchanged by all queries and rendering');
echo "Completed ".$count." integration assertions.\n";
